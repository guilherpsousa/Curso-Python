'''
OPERADORES DE COMPARAÇÃO (RELACIONAIS)

OP      SIGNIFICADO         EXEMPLO (true)
>       maior               2 > 1
>=      maior ou igual      2 >= 2
<       menor               1 < 2
<=      menor ou igual      2 <= 2
==      igual               'a' == 'a'
!=      diferente           'a' != 'b'

'''

