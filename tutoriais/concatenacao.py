# Concatenacão é operações lógicas que envolvem strings, ou seja, a junção de duas ou mais strings.
concatenacao = 'Guilherme' + ' ' + 'Pontes'
print(concatenacao)

guilhermerepetido = 'Guilherme' * 3
print(guilhermerepetido) 

# Se tiver números no meio, eu preciso converter para string.
concatenacao2 = 'Guilherme' + str(2) + 'Pontes'
print(concatenacao2)
