# OPERADORES 
# Não se esquecer da precedência dos operadores, que é a ordem que eles são executados.
# 1. (n+n)   2. **   3. * e /   4. + e - 

# RESTO DA DIVISÃO.
resto_divisao = 10 % 2 # 10 dividido por 2 não tem resto, então o resultado é 0.
print('Resto da Divisão:', resto_divisao)
print('O número é par?:', 10%2==0) # == Vai me retornar True ou False se 10 dividido por 2 tem resto 0.
# pra saber se um número é par ou ímpar, posso usar o resto da divisão por 2.

adicao = 10 + 5
print('Adição:', adicao)

subtracao = 10 - 5
print('Subtração:', subtracao)

multiplicacao = 10 * 5
print('Multiplicação:', multiplicacao)

divisao = 10 / 5 # divisão normal, sempre retorna float (2.0)
print('Divisão:', divisao)

divisao_inteira = 10 // 5 # divisão inteira, retorna apenas o número inteiro (2)
print('Divisão Inteira:', divisao_inteira)

exponenciacao = 10 ** 2 # exponenciação, 10 elevado a 2
print('Exponenciação:', exponenciacao)

