"""
STRING -> são dados que representam textos, 
dentro de aspas simples ou duplas.
"""
print('Hello, world!') # aspas simples
"""
Para simplificar o uso das aspas, para que possam aparecer,
posso usar aspas simples dentro de duplas, e vice-versa.
"""
print('"Hello, world!"')

"""
ESCAPE -> É um recurso que me permite escrever caracteres especiais
sem o editor interpretar como um comando.
"""
print("Guilherme \"Pontes\"") # Demonstrando o uso do \ 
print(r"Guilherme \"Pontes\"") # O "r" permite que apareça a \ 